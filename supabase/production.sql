-- Audit direct admin changes to master data and settlement rows.
create or replace function public.audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
  v_details jsonb;
begin
  if tg_op='DELETE' then v_id:=old.id; else v_id:=new.id; end if;
  v_details := jsonb_build_object(
    'operation',tg_op,
    'before',case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) else null end,
    'after',case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) else null end
  );
  perform public.write_audit(lower(tg_op),tg_table_name,v_id,v_details);
  if tg_op='DELETE' then return old; else return new; end if;
end;
$$;

